export const messages = { "zh-CN": zhCN, "zh-TW": zhTW, en, ja };
type Values = Record<string, string | number>;

export function translate(
  key: MessageKey,
  locale: UiLocale = "zh-CN",
  values: Values = {},
): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (token, name: string) =>
    String(values[name] ?? token),
  );
}

export function loadUiLocale(): UiLocale {
  try {
    const stored = localStorage.getItem(UI_LOCALE_KEY);
    return LANGUAGE_OPTIONS.find(({ value }) => value === stored)?.value ?? "zh-CN";
  } catch {
    return "zh-CN";
  }
}

const I18nContext = createContext<{
  locale: UiLocale;
  setLocale: (locale: UiLocale) => void;
  t: (key: MessageKey, values?: Values) => string;
}>({
  locale: "zh-CN",
  setLocale: () => {},
  t: (key: MessageKey, values?: Values) => translate(key, "zh-CN", values),
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState(loadUiLocale);
  useEffect(() => {
    document.documentElement.lang = locale;
    try {
      localStorage.setItem(UI_LOCALE_KEY, locale);
    } catch {
      // Language switching remains available when storage is blocked.
    }
  }, [locale]);
  const t = useCallback(
    (key: MessageKey, values?: Values) => translate(key, locale, values),
    [locale],
  );
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
